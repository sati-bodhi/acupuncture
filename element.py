        """Get the cardinal point 本穴 of a certain meridian."""

        db = Database()
        self.acupoint = db.exec_script(f"""
        SELECT ID, elem FROM Pentashu
        WHERE meridian_id = "{m}" and cardinal = "1";
        """)

        return self.acupoint[0]

