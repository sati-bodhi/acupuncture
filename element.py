        """Get attributes of Pentashu acupoint."""
        db = Database()
        self.attrib = db.exec_script(f"""
        SELECT name, meridian_abbrev, elem FROM Pentashu
        WHERE ID = "{acupoint}";
        """)[0]
        return self.attrib[1] + self.attrib[2] + "穴"


