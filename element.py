class Season(Element):
    SEASONS = ["春", "夏", "秋", "冬"]
    SEASON_ENERGY = {
        "春": "木",
        "夏": "火",
        "秋": "金",
        "冬": "水",
    }

    def __init__(self):

        self.season_label = None
        self.earth_energy = None
        self.organ = None
        self.solar_term_date = None
        self.tz = solartime_by_ip()[1]
        self.tz = ZoneInfo(self.tz)  # current time zone, based on ip.
        self.current_date = datetime.now(self.tz)
        self.yr = datetime.now(self.tz).year
        self.db_yr = None

        self.season = None
        self.solar_term = None
        self.season_df = None
        self.solar_term_df = None
        self.season_array = None
        self.terms_array = None

    def update_solar_term_data(self):
        """Check whether solar term data in acu.db is up-to-date."""

        db = Database()
        self.db_yr = db.exec_script("""
        SELECT date_utc FROM seasons WHERE solar_term = "春分";
        """)

        if self.yr != self.db_yr:
            self.build_season_data()

    def load_solar_term_data(self):
        """Load solar term data from skyfield.
        This should be automatically updated once every calendar year."""

        ts = load.timescale()
        eph = load('de421.bsp')  # Covers 1900-2050; use de422 for Chinese History Project

        t0 = ts.utc(self.yr, 1, 1)
        t1 = ts.utc(self.yr, 12, 31)  # relative date one month from now
        t, tm = almanac.find_discrete(t0, t1, almanac_ea.solar_terms(eph))

        solar_term = []
        date = []
        for tmi, ti in zip(tm, t):
            solar_term.append(almanac_ea.SOLAR_TERMS_ZHT[tmi])
            date.append(ti.utc_datetime())

        self.solar_term_df = pd.DataFrame(list(zip(solar_term, date)), columns=["solar_term", "date_utc"])

        return self.solar_term_df

    def season_solar_terms(self):
        jieqi_terms = almanac_ea.SOLAR_TERMS_ZHT[-3:] + almanac_ea.SOLAR_TERMS_ZHT[:-3]
        jieqi_season = [[season] * 6 for season in self.SEASONS]
        jieqi_season = [item for sublist in jieqi_season for item in sublist]

        self.terms_array = np.array(jieqi_terms)
        self.season_array = np.array(jieqi_season)

        return self.terms_array, self.season_array

    def build_season_data(self):

        terms_array, season_array = self.season_solar_terms()
        season_energy = np.vectorize(self.SEASON_ENERGY.get)(list(season_array))
        season_change = np.where(season_array[:-1] != season_array[1:])[
            0]  # 大寒、穀雨、大暑、霜降。「立春」等前一個節氣，約換季前十八天。屬土，宜補脾。《素問·太陰陽明論》：“脾者土也，治中央，常以四時長四藏，各十八日寄治，不得獨主於時也。”

        if season_array[1] != season_array[-1]:
            season_change = np.append(season_change, 23)

        season_dict = {
            "solar_term": terms_array,
            "season": season_array,
            "long_summer": [True if term in ["大暑", "立秋", "處暑"] else False for term in terms_array],  # 夏末跨季一個月
            "energy_5elem": season_energy,
            "earth_energy": [True if term in terms_array[season_change] else False for term in terms_array],
        }  # merge long_summer and inter-season earth_energy to get best timing for treating the spleen.

        season_df = pd.DataFrame(season_dict)
        solar_term_df = self.load_solar_term_data()
        self.season_df = pd.merge(season_df, solar_term_df, on='solar_term', how='outer')

        db = Database()
        db.df_to_sql(self.season_df, "seasons")

        return self.season_df

    def current_season(self):
        """Return current season, the last solar term (節氣) and the present date."""

        db = Database()
        jieqi = db.exec_script("""
                    SELECT solar_term, season, date_utc, long_summer FROM seasons;
                    """)
        dates = [dt for tm, sn, dt, ls in jieqi]

        for i, dt in enumerate(dates):
            if i + 1 <= len(dates):
                lower_bound = datetime.fromisoformat(dt)
                upper_bound = datetime.fromisoformat(dates[i + 1])

                if lower_bound <= self.current_date < upper_bound:
                    self.solar_term = jieqi[i][0]
                    self.solar_term_date = datetime.fromisoformat(jieqi[i][2]).astimezone(self.tz)
                    self.season = jieqi[i][1]
                    if self.season == "夏" or self.season == "秋" and jieqi[i][3] == 1:
                        self.season_label = self.season + f"（長夏）"
                    else:
                        self.season_label = self.season

                    return self.season, self.solar_term, self.solar_term_date, \
                        self.current_date.astimezone(self.tz), self.tz, self.season_label
            else:
                break

    def seasonal_lord(self, season):
        """Get seasonal lord (organ energy) from season."""
        self.organ = [o for e, s, o, p, b in self.ELEM_CORRESPOND if s == season]
        return self.organ[0]

    def earth_energy_timeframe(self, solar_term):
        """Returns True if season is within the earth energy time frame,
        suitable for treating the Spleen."""

        db = Database()
        self.earth_energy = db.exec_script(f"""
        SELECT earth_energy, long_summer FROM seasons
        WHERE solar_term = "{solar_term}";
        """)[0]
        
        if 1 in self.earth_energy:
            return True


