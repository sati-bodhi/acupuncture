        """Get Pentashu acupoint of a certain meridian
        belonging to a certain element."""

        db = Database()
        self.acupoint = db.exec_script(f"""
        SELECT ID FROM Pentashu
        WHERE meridian_id = "{x}" and elem = "{y}";
        """)

        return self.acupoint[0][0]

