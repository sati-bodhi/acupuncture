        """Enhance the energetic connection between the lord organ and
        one of its relatives."""

        relative_list = ["mother", "son", "minister"]
        if relative and relative in relative_list:

            p = Pentashu()
            jun = Lord(lord)

            cardinal_lord = p.cardinal_point_of_meridian(lord)
            mother = jun.mother
            son = jun.son
            minister = jun.minister

            if relative == "mother":
                relative = mother
            elif relative == "son":
                relative = son
            elif relative == "minister":
                relative = minister

            cardinal_relative = p.cardinal_point_of_meridian(relative)

            self.formula = []

            # 補關係臟腑與君本穴屬性相同的五輸穴
            self.formula.append((p.acupoint_of_x_meridian_with_y_qualities(
                relative, cardinal_lord[1]), "++"))
